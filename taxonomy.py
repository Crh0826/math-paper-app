CHAPTER_NAMES = {c: f"{c.split(' ')[0]}综合" for c in CHAPTER_ORDER if c != "综合"}

UNCLASSIFIED = ("9.3", "综合", "未分类")

_TITLE_C = [(cid, ch, name, re.compile(pat)) for cid, ch, name, pat in TITLE_RULES]
_TEXT_C = [(cid, ch, name, re.compile(pat)) for cid, ch, name, pat in TEXT_RULES]


def _first_match(rules, s: str) -> Optional[Tuple[str, str, str]]:
    for cid, ch, name, rx in rules:
        if rx.search(s):
            return cid, ch, name
    return None


_CHAPTER_RX = [(ch, re.compile(pat)) for ch, pat in CHAPTER_HINTS]


def chapter_hint(s: str) -> Optional[str]:
    """只给得出章时返回章名；给了两章以上（如"第1~3章"）视为混合，返回 None。"""
    hits = [ch for ch, rx in _CHAPTER_RX if rx.search(s or "")]
    if len(hits) == 1:
        return hits[0]
    return None


def _chapter_level(ch: str) -> Dict[str, str]:
    num = ch.split(" ")[0].replace("第", "").replace("章", "")
    return {"kp_id": f"{num}.0", "chapter": ch,
            "kp": f"{ch.split(' ')[1]}·综合", "source": "chapter"}


def classify(title: str, text: str = "") -> Dict[str, str]:
    """返回 {kp_id, chapter, kp, source}，source ∈ title/text/chapter/none。"""
    title = title or ""
    t_hit = _first_match(_TITLE_C, title)
    x_hit = _first_match(_TEXT_C, text or "")

    # 具体知识点优先；标题的具体知识点最可信
    if t_hit and not t_hit[0].startswith("9."):
        return {"kp_id": t_hit[0], "chapter": t_hit[1], "kp": t_hit[2], "source": "title"}
    if x_hit:
        return {"kp_id": x_hit[0], "chapter": x_hit[1], "kp": x_hit[2], "source": "text"}
    if t_hit:  # 只剩 9.x 粗分类
        return {"kp_id": t_hit[0], "chapter": t_hit[1], "kp": t_hit[2], "source": "title"}

    # 章级兜底
    ch = chapter_hint(title) or chapter_hint((text or "")[:200])
    if ch:
        return _chapter_level(ch)
    return {"kp_id": UNCLASSIFIED[0], "chapter": UNCLASSIFIED[1], "kp": UNCLASSIFIED[2], "source": "none"}


def all_kps() -> List[dict]:
    seen, out = set(), []
    for cid, ch, name, _ in TITLE_RULES:
        if cid in seen:
            continue
        seen.add(cid)
        out.append({"kp_id": cid, "chapter": ch, "kp": name})
    for ch in CHAPTER_ORDER:
        if ch == "综合":
            continue
        d = _chapter_level(ch)
        if d["kp_id"] not in seen:
            seen.add(d["kp_id"])
            out.append({"kp_id": d["kp_id"], "chapter": ch, "kp": d["kp"]})
    out.append({"kp_id": UNCLASSIFIED[0], "chapter": UNCLASSIFIED[1], "kp": UNCLASSIFIED[2]})
    out.sort(key=lambda x: (CHAPTER_ORDER.get(x["chapter"], 99), float(x["kp_id"])))
    return out
